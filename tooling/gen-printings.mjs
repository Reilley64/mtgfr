// Generate the pool's printing records from Scryfall, and strip what they now own from the card TOMLs.
//
// Flavor text belongs to a printing, not to a card: a deck that plays a reprint prints different
// words under the same rules. So the card TOML carries none, and every printing gets a record the
// API joins on by Printing UUID (`ObjectView.print`). The card's `sets` list is derived from these
// records at load rather than written twice.
//
// One file per card rather than per printing: the pool is ~1040 cards but tens of thousands of
// printings, and the join only ever goes by id. A printing that prints no flavor still gets a
// record — it is what tells the pool the card was printed in that set.
//
// Reads Scryfall's `default_cards` bulk file (one JSON object per line, one line per printing)
// rather than a search per card: 1040 paged searches gets you rate-limited, and Scryfall asks for
// bulk for exactly this.
//
// Idempotent + re-runnable: rewrites `crates/cards/data/prints/` and re-strips the card TOMLs.
// Run from the repo root:  node tooling/gen-printings.mjs

import { createReadStream, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createInterface } from "node:readline";
import { dirname, join } from "node:path";
import { Readable } from "node:stream";
import { fileURLToPath } from "node:url";
import { createGunzip } from "node:zlib";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DATA_DIR = join(ROOT, "crates/cards/data");
const PRINTS_DIR = join(DATA_DIR, "prints");
const UA = { "User-Agent": "edh.reilley.dev/0.1", Accept: "application/json" };

// A local copy of the bulk file, for re-runs that should not re-download 77MB.
const cached = (() => {
  const at = process.argv.indexOf("--bulk");
  return at < 0 ? null : process.argv[at + 1];
})();

// The front face's flavor: a card prints one block per face, and a face renders its own.
function flavorOf(card) {
  if (typeof card.flavor_text === "string") return card.flavor_text;
  if (Array.isArray(card.card_faces)) return card.card_faces[0]?.flavor_text ?? "";
  return "";
}

// A single-line TOML basic string: escape backslashes, quotes, and newlines (flavor runs to
// several lines, and an attribution sits on its own). Matches what `oracle` already does.
const tomlStr = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, "\\n")}"`;

const nameOf = (text) => text.match(/^\s*name\s*=\s*"((?:[^"\\]|\\.)*)"/m)?.[1];
const idOf = (text) => text.match(/^\s*id\s*=\s*"([^"]+)"/m)?.[1];

async function bulkLines() {
  if (cached) return createInterface({ input: createReadStream(cached).pipe(createGunzip()) });

  const index = await fetch("https://api.scryfall.com/bulk-data", { headers: UA });
  if (!index.ok) throw new Error(`Scryfall bulk-data ${index.status}`);
  const entry = (await index.json()).data.find((d) => d.type === "default_cards");
  const file = await fetch(entry.jsonl_download_uri, { headers: UA });
  if (!file.ok) throw new Error(`Scryfall bulk download ${file.status}`);
  return createInterface({ input: Readable.fromWeb(file.body).pipe(createGunzip()) });
}

function writePrintings(slug, name, oracleId, printings) {
  const lines = [
    `# ${name} — every printing, oldest first. Generated by tooling/gen-printings.mjs.`,
    `card = ${tomlStr(oracleId)}`,
  ];
  for (const p of printings) {
    lines.push("", "[[printings]]", `id = ${tomlStr(p.id)}`, `set = ${tomlStr(p.set)}`);
    if (p.flavor !== "") lines.push(`flavor = ${tomlStr(p.flavor)}`);
  }
  writeFileSync(join(PRINTS_DIR, `${slug}.toml`), `${lines.join("\n")}\n`);
}

// Drop the keys the printing records now own: `flavor` (per printing, never per card) and `sets`
// (derived from the records at load). Top-level only — before the first table.
function stripDerivedKeys(path) {
  const text = readFileSync(path, "utf8");
  const lines = text.split("\n");
  const firstTable = lines.findIndex((l) => /^\s*\[/.test(l));
  const cut = firstTable < 0 ? lines.length : firstTable;
  const kept = lines.filter((l, i) => !(i < cut && /^\s*(flavor|sets)\s*=/.test(l)));
  if (kept.length === lines.length) return false;
  writeFileSync(path, kept.join("\n"));
  return true;
}

const cards = new Map();
for (const file of readdirSync(DATA_DIR).filter((f) => f.endsWith(".toml"))) {
  const path = join(DATA_DIR, file);
  const text = readFileSync(path, "utf8");
  const oracleId = idOf(text);
  if (oracleId == null) continue;
  const slug = file.replace(/\.toml$/, "");
  cards.set(oracleId, { slug, path, name: nameOf(text) ?? slug, printings: [] });
}

let scanned = 0;
for await (const line of await bulkLines()) {
  if (line.length < 2) continue;
  scanned += 1;
  const card = JSON.parse(line.replace(/,\s*$/, ""));
  const entry = cards.get(card.oracle_id);
  if (entry == null) continue;
  entry.printings.push({ id: card.id, set: card.set, released: card.released_at ?? "", flavor: flavorOf(card) });
}

rmSync(PRINTS_DIR, { recursive: true, force: true });
mkdirSync(PRINTS_DIR, { recursive: true });

let written = 0;
let stripped = 0;
let printings = 0;
const missing = [];
for (const [oracleId, entry] of cards) {
  if (entry.printings.length === 0) {
    missing.push(entry.slug);
    continue;
  }
  // Oldest first, then by id so a set's own printings land in a stable order across runs.
  entry.printings.sort((a, b) => a.released.localeCompare(b.released) || a.id.localeCompare(b.id));
  writePrintings(entry.slug, entry.name, oracleId, entry.printings);
  written += 1;
  printings += entry.printings.length;
  if (stripDerivedKeys(entry.path)) stripped += 1;
}

console.log(`scanned ${scanned} printings`);
console.log(`${written} print files (${printings} printings), stripped keys from ${stripped} card TOMLs`);
if (missing.length > 0) console.log(`no printings found for ${missing.length}: ${missing.join(", ")}`);
