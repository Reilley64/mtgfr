use std::{fs, path::Path, process::ExitCode};

use serde_json::{Map, Value};

const REFERENCE_PATH: &str = ".agents/skills/card-dsl/DSL_REFERENCE.md";

fn main() -> ExitCode {
    let check = std::env::args().any(|arg| arg == "--check");
    let rendered = render_reference();

    if write_or_check(REFERENCE_PATH, &rendered, check) {
        return ExitCode::FAILURE;
    }

    ExitCode::SUCCESS
}

fn render_reference() -> String {
    let schema = serde_json::to_value(schemars::schema_for!(cards::toml_surface::CardToml))
        .expect("CardToml schema serializes");
    let doc = DslReference::new(schema);

    let mut out = String::new();
    out.push_str("# Card-Definition TOML DSL Reference\n\n");
    out.push_str("<!-- GENERATED FILE: do not edit by hand. -->\n\n");
    out.push_str(
        "Generated by `just cards-dsl-ref` from `cards::toml_surface::CardToml` \
         using `schemars` and rustdoc descriptions.\n\n",
    );
    out.push_str(
        "For §0 Oracle-text comments, `approximates`, and `# ponytail:` process \
         discipline, read [`SKILL.md`](SKILL.md).\n\n",
    );

    doc.render_properties("## CardToml top-level properties", doc.root(), &mut out);
    doc.render_properties("## CostToml", doc.definition("CostToml"), &mut out);
    doc.render_kind(&mut out);
    doc.render_effect_types(&mut out);

    while out.ends_with("\n\n") {
        out.pop();
    }

    out
}

struct DslReference {
    schema: Value,
}

impl DslReference {
    fn new(schema: Value) -> Self {
        Self { schema }
    }

    fn root(&self) -> &Value {
        &self.schema
    }

    fn definition(&self, name: &str) -> &Value {
        let defs = self
            .schema
            .get("definitions")
            .or_else(|| self.schema.get("$defs"))
            .and_then(Value::as_object)
            .expect("schema definitions");
        defs.get(name)
            .unwrap_or_else(|| panic!("missing schema definition {name}"))
    }

    fn render_properties(&self, heading: &str, schema: &Value, out: &mut String) {
        out.push_str(heading);
        out.push_str("\n\n");

        if let Some(description) = description(schema) {
            out.push_str(description);
            out.push_str("\n\n");
        }

        out.push_str("| Field | Type | Required | Default | Description |\n");
        out.push_str("|---|---|---:|---|---|\n");

        let properties = schema
            .get("properties")
            .and_then(Value::as_object)
            .expect("schema properties");
        let required = required_fields(schema);

        for (name, property) in properties {
            out.push_str("| `");
            out.push_str(&escape_markdown(name));
            out.push_str("` | ");
            out.push_str(&escape_markdown(&type_summary(property)));
            out.push_str(" | ");
            out.push_str(if required.contains(&name.as_str()) {
                "yes"
            } else {
                "no"
            });
            out.push_str(" | ");
            out.push_str(&escape_markdown(&default_summary(property)));
            out.push_str(" | ");
            out.push_str(&escape_markdown(description(property).unwrap_or("")));
            out.push_str(" |\n");
        }

        out.push('\n');
    }

    fn render_kind(&self, out: &mut String) {
        let schema = self.definition("KindToml");
        out.push_str("## KindToml\n\n");

        if let Some(description) = description(schema) {
            out.push_str(description);
            out.push_str("\n\n");
        }

        out.push_str("| `type` | Required fields | Optional fields | Description |\n");
        out.push_str("|---|---|---|---|\n");

        let variants = schema
            .get("oneOf")
            .and_then(Value::as_array)
            .expect("KindToml variants");

        for variant in variants {
            let properties = variant
                .get("properties")
                .and_then(Value::as_object)
                .expect("KindToml variant properties");
            let tag = tag_value(properties).expect("KindToml type tag");
            let required = required_fields(variant);
            let mut required_fields = Vec::new();
            let mut optional_fields = Vec::new();

            for name in properties.keys().filter(|name| name.as_str() != "type") {
                if required.contains(&name.as_str()) {
                    required_fields.push(format!("`{}`", escape_markdown(name)));
                    continue;
                }
                optional_fields.push(format!("`{}`", escape_markdown(name)));
            }

            out.push_str("| `");
            out.push_str(&escape_markdown(tag));
            out.push_str("` | ");
            out.push_str(&empty_dash(&required_fields.join(", ")));
            out.push_str(" | ");
            out.push_str(&empty_dash(&optional_fields.join(", ")));
            out.push_str(" | ");
            out.push_str(&escape_markdown(description(variant).unwrap_or("")));
            out.push_str(" |\n");
        }

        out.push('\n');
    }

    fn render_effect_types(&self, out: &mut String) {
        let schema = self.definition("EffectTypeTomlSchema");
        out.push_str("## Effect `type` enum variants\n\n");
        out.push_str("Each `[[abilities.effects]]` entry has a `type` family tag. Leaf modes and payload fields are still documented by the concrete effect rustdoc as Wave C expands the schema surface.\n\n");
        out.push_str("| `type` | Description |\n");
        out.push_str("|---|---|\n");

        for (variant, description) in effect_variants(schema) {
            out.push_str("| `");
            out.push_str(&escape_markdown(variant));
            out.push_str("` | ");
            out.push_str(&escape_markdown(description));
            out.push_str(" |\n");
        }

        out.push('\n');
    }
}

fn required_fields(schema: &Value) -> Vec<&str> {
    schema
        .get("required")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
        .collect()
}

fn description(schema: &Value) -> Option<&str> {
    schema.get("description").and_then(Value::as_str)
}

fn enum_values(schema: &Value) -> impl Iterator<Item = &str> {
    schema
        .get("enum")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(Value::as_str)
}

fn effect_variants(schema: &Value) -> Vec<(&str, &str)> {
    if let Some(one_of) = schema.get("oneOf").and_then(Value::as_array) {
        let rows: Vec<_> = one_of
            .iter()
            .filter_map(|variant| {
                let value = enum_values(variant).next()?;
                let description = description(variant).unwrap_or(effect_type_description(value));
                Some((value, description))
            })
            .collect();
        if !rows.is_empty() {
            return rows;
        }
    }

    enum_values(schema)
        .map(|value| (value, effect_type_description(value)))
        .collect()
}

fn tag_value(properties: &Map<String, Value>) -> Option<&str> {
    properties
        .get("type")?
        .get("enum")?
        .as_array()?
        .first()?
        .as_str()
}

fn type_summary(schema: &Value) -> String {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        return reference
            .rsplit('/')
            .next()
            .expect("schema ref name")
            .to_owned();
    }

    if let Some(any_of) = schema.get("anyOf").and_then(Value::as_array) {
        let parts: Vec<_> = any_of.iter().map(type_summary).collect();
        return parts.join(" | ");
    }

    if let Some(one_of) = schema.get("oneOf").and_then(Value::as_array) {
        let parts: Vec<_> = one_of.iter().map(type_summary).collect();
        return parts.join(" | ");
    }

    if let Some(all_of) = schema.get("allOf").and_then(Value::as_array) {
        let parts: Vec<_> = all_of.iter().map(type_summary).collect();
        return parts.join(" & ");
    }

    if let Some(items) = schema.get("items") {
        return format!("array<{}>", type_summary(items));
    }

    match schema.get("type") {
        Some(Value::String(kind)) => kind.to_owned(),
        Some(Value::Array(kinds)) => kinds
            .iter()
            .filter_map(Value::as_str)
            .collect::<Vec<_>>()
            .join(" | "),
        Some(_) | None => "any".to_owned(),
    }
}

fn default_summary(schema: &Value) -> String {
    match schema.get("default") {
        Some(Value::Null) => "`null`".to_owned(),
        Some(Value::String(text)) => format!("`{text}`"),
        Some(value) => format!("`{value}`"),
        None => "-".to_owned(),
    }
}

fn empty_dash(text: &str) -> String {
    if text.is_empty() {
        return "-".to_owned();
    }
    text.to_owned()
}

fn escape_markdown(text: &str) -> String {
    text.replace('\n', "<br>")
        .replace('|', "\\|")
        .replace('\r', "")
}

fn effect_type_description(variant: &str) -> &'static str {
    match variant {
        "damage" => "Damage effects such as targeted damage and mass creature damage.",
        "draw" => "Card draw effects for one player, target players, or each player.",
        "life" => "Life gain, life loss, drain, and life-payment riders.",
        "destroy" => "Destroy effects for targets, filtered groups, and damaged objects.",
        "exile" => "Exile effects for targets, graveyards, and until-source-leaves zones.",
        "sacrifice" => "Sacrifice effects for the source or other specified permanents.",
        "control" => "Tap, untap, goad, equip, and control-changing effects.",
        "counters" => "Add, remove, move, and count counters.",
        "mana" => "Mana production effects.",
        "mill" => "Mill and impulse-exile-from-library effects.",
        "pump" => "Temporary or base power/toughness modifications.",
        "reveal" => "Reveal effects.",
        "token" => "Token creation and copy-token effects.",
        "zone" => "Move cards or permanents between zones.",
        "copy" => "Copy spells, abilities, or objects.",
        "dig" => "Search, scry, surveil, cascade, clash, and top-library selection.",
        "choice" => "Resolution-time choices such as may-sacrifice, discard, and proliferate.",
        "static" => "Continuous static effects and replacement effects.",
        "misc" => "Specialized effects that do not fit a broader family yet.",
        "sequence" => "Run multiple effects in order.",
        "choose_one" => "Choose one effect branch during resolution.",
        "conditional" => "Run effects only when a condition holds, with optional otherwise steps.",
        _ => "",
    }
}

fn write_or_check(path: &str, rendered: &str, check: bool) -> bool {
    let path = Path::new(path);

    if !check {
        fs::create_dir_all(path.parent().expect("reference parent")).expect("create reference dir");
        fs::write(path, rendered).expect("write DSL reference");
        return false;
    }

    match fs::read_to_string(path) {
        Ok(existing) if existing == rendered => false,
        Ok(_) => {
            eprintln!("{} is stale; run `just cards-dsl-ref`", path.display());
            true
        }
        Err(err) => {
            eprintln!("{} is missing or unreadable: {err}", path.display());
            true
        }
    }
}
